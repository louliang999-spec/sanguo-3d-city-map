/** 与某城直接相连的城池下标列表 */
export function neighborsOf(i) {
  return ROADS.filter(([a, b]) => a === i || b === i).map(([a, b]) => (a === i ? b : a));
}

/* ------------------------------------------------------------
 * 补全派生字段(城型 / 数值)
 * ---------------------------------------------------------- */
export const CITIES = CITY_LIST.map((c, i) => {
  const g = GRADE_STATS[c.grade];
  return {
    ...c,
    index: i,
    type: c.type || g.type,
    gradeName: g.name,
    gradeDesc: g.desc,
    defense: g.defense,
    garrison: g.garrison,
    gold: g.gold,
    food: g.food,
    generals: g.generals,
  };
});

/** 每州多少城(给图例 / 统计用) */
export function zhouSummary() {
  const m = new Map();
  CITIES.forEach((c) => m.set(c.zhou, (m.get(c.zhou) || 0) + 1));
  return [...m.entries()].map(([zhou, count]) => ({ zhou, count }));
}

/** 每级多少城 */
export function gradeSummary() {
  return GRADE_ORDER.map((k) => ({
    key: k,
    ...GRADE_STATS[k],
    count: CITIES.filter((c) => c.grade === k).length,
  }));
}
